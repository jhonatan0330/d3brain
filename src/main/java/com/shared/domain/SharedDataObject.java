package com.shared.domain;

public abstract class SharedDataObject {

	private String key;
	
	private String state;

	public String getKey() {
		return key;
	}

	public void setKey(String key) {
		this.key = key;
	}

	public String getState() {
		return state;
	}

	public void setState(String state) {
		this.state = state;
	}

}
